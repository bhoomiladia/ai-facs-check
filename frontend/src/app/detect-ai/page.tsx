'use client'

import { useState } from 'react'
import { Header } from '@/components/Header'
import { AITextDetection } from '@/components/AITextDetection'
import { AITextDetectionResult } from '@/types'
import { Button } from '@/components/ui/button'
import { Textarea } from '@/components/ui/textarea'
import { Fingerprint, ArrowRight, Download } from 'lucide-react'
import { exportAITextAsPDF } from '@/lib/export-pdf'

export default function DetectAIPage() {
  const [text, setText] = useState('')
  const [isAnalyzing, setIsAnalyzing] = useState(false)
  const [result, setResult] = useState<AITextDetectionResult | null>(null)
  const [error, setError] = useState<string | null>(null)

  const handleAnalyze = async () => {
    if (text.trim().length < 50) {
      setError('Please enter at least 50 characters of text for meaningful analysis.')
      return
    }

    setIsAnalyzing(true)
    setError(null)
    setResult(null)

    try {
      const response = await fetch('/api/detect-ai', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ text: text.trim() }),
      })

      if (!response.ok) {
        const errorData = await response.json()
        throw new Error(errorData.error || 'Failed to analyze text')
      }

      const data = await response.json()
      setResult(data)
    } catch (err) {
      console.error(err)
      setError(err instanceof Error ? err.message : 'An unknown error occurred')
    } finally {
      setIsAnalyzing(false)
    }
  }

  const today = new Date().toLocaleDateString('en-US', { weekday: 'long', year: 'numeric', month: 'long', day: 'numeric' })

  return (
    <div className="min-h-screen relative overflow-x-hidden pt-4 pb-12">
      <div className="relative z-10">
        <main className="container mx-auto px-4 lg:px-8 max-w-6xl">
          <div className="text-center mb-8">
            <div className="double-border-y py-2 mb-4 flex justify-between items-center text-sm font-bold uppercase tracking-widest text-foreground/80">
              <span>Vol. I — No. 1</span>
              <span>{today}</span>
              <span>Price: Free Truth</span>
            </div>
            <h1 className="text-5xl md:text-7xl lg:text-8xl font-black uppercase tracking-tighter text-foreground mb-2" style={{ fontFamily: 'var(--font-playfair-display), serif' }}>
              The Daily Verifier
            </h1>
            <h2 className="text-xl md:text-2xl font-serif italic text-foreground/70 mb-6">
              "Bringing absolute clarity to a world of noise."
            </h2>
            <div className="w-full h-1 bg-foreground mb-1"></div>
            <div className="w-full h-0.5 bg-foreground mb-8"></div>
          </div>

          <Header />

          <div className="max-w-4xl mx-auto mt-8 animate-slide-up">
            <div className="mb-8">
              <h2 className="text-3xl font-black text-foreground tracking-tight uppercase border-b-2 border-foreground pb-2 flex items-center gap-2">
                <Fingerprint className="h-8 w-8" />
                AI Authorship Analysis
              </h2>
              <p className="text-lg text-foreground/80 mt-4 font-serif italic">
                Paste an article, essay, or email below. Our forensic computational linguist engine will analyze perplexity, burstiness, syntax, and stylistic markers to determine if the text was written by a human or generated by an AI model.
              </p>
            </div>

            <div className="panel p-6 mb-8 bg-card">
              <Textarea
                placeholder="Paste the text you want to analyze here... (Minimum 50 characters)"
                value={text}
                onChange={(e) => setText(e.target.value)}
                className="min-h-[250px] bg-background border-2 border-foreground text-foreground text-base p-4 resize-y rounded-none mb-4 font-serif"
              />
              
              {error && (
                <div className="mb-4 p-3 bg-red-50 border-l-4 border-red-700 text-red-900 text-sm font-bold">
                  {error}
                </div>
              )}

              <div className="flex justify-between items-center">
                <span className="text-xs font-bold text-foreground/50 uppercase tracking-widest">
                  {text.length} Characters
                </span>
                
                <Button
                  onClick={handleAnalyze}
                  disabled={isAnalyzing || text.trim().length === 0}
                  className="btn-verify h-12 text-content px-8 text-base"
                >
                  {isAnalyzing ? (
                    <>
                      <div className="inline-block ai-detection-spinner mr-3 w-5 h-5 border-2 border-t-background" style={{ borderColor: 'rgba(255,255,255,0.2)', borderTopColor: 'white' }} />
                      Analyzing...
                    </>
                  ) : (
                    <>
                      Start Analysis
                      <ArrowRight className="h-5 w-5 ml-2" />
                    </>
                  )}
                </Button>
              </div>
            </div>

            {result && (
              <div className="animate-slide-up mt-8">
                <div className="flex justify-between items-end mb-4 border-b-2 border-foreground pb-2">
                  <h3 className="text-2xl font-black uppercase text-foreground">
                    The Analyst's Report
                  </h3>
                  <Button variant="outline" size="sm" onClick={() => exportAITextAsPDF(result)} className="border-2 border-foreground hover:bg-foreground hover:text-background transition-colors font-bold uppercase tracking-widest text-xs h-8">
                    <Download className="mr-2 h-3 w-3" />
                    Export PDF
                  </Button>
                </div>
                <AITextDetection result={result} />
              </div>
            )}
          </div>
        </main>
      </div>
    </div>
  )
}
